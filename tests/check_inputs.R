# Base-R integrity and routing check; does not fit models or load private data.
file_argument <- grep("^--file=",commandArgs(FALSE),value=TRUE)
stopifnot(length(file_argument)==1L)
code_root <- dirname(dirname(normalizePath(sub("^--file=","",file_argument),winslash="/")))
if (.Platform$OS.type=="windows") invisible(Sys.setlocale("LC_CTYPE","English_United States.utf8"))
source(file.path(code_root,"config/config.R"))
source(file.path(code_root,"R/paths.R"))
source(file.path(code_root,"R/output_names.R"))
source(file.path(code_root,"R/bundled_inputs.R"))
ppi_initialize(code_root,data_root,tempfile("ppi_input_check_"),external)
manifest <- read.csv(file.path(data_root,"input_manifest.csv"),stringsAsFactors=FALSE)
stopifnot(!anyDuplicated(manifest$logical_path))
paths <- file.path(data_root,manifest$package_path)
stopifnot(all(file.exists(paths)),all(ppi_under(paths,data_root)))
stopifnot(all(as.numeric(file.info(paths)$size)==as.numeric(manifest$bytes)))
resolved <- vapply(manifest$logical_path,function(x)ppi_input(ppi_path(x)),character(1))
stopifnot(all(normalizePath(resolved,winslash="/")==normalizePath(paths,winslash="/")))
for (p in list.files(file.path(code_root,"scripts"),pattern="\\.R$",recursive=TRUE,full.names=TRUE))
    parse(p,encoding="UTF-8")
index <- read.csv(file.path(code_root,"config/entries.csv"),stringsAsFactors=FALSE)
stopifnot(all(file.exists(file.path(code_root,index$script))))
workflows <- read.csv(file.path(code_root,"config/workflows.csv"),stringsAsFactors=FALSE)
stopifnot(all(workflows$script %in% basename(index$script)))
cat(nrow(manifest),"input aliases resolve within data/; sizes and script parsing pass.\n")
cat("SHA-256 hashes are recorded in data/input_manifest.csv for external verification.\n")
